/**
 * Почему действие в кабинете не прошло, — значением, о котором договорились
 * обе стороны.
 *
 * Причина та же, что у `AUTH_ERROR_CODES` и `BOOKING_ERROR_CODES`, но повод
 * другой и он важнее: те экраны работают до входа, а этот — после, и язык
 * мастера продукту уже известен. Тем заметнее было расхождение. Сообщения
 * `NestJS` написаны по-русски, кабинет говорит на трёх языках, и два экрана
 * печатали серверную фразу дословно: английская форма записи отвечала
 * «Это время уже прошло».
 *
 * По HTTP-статусу эти отказы не различить — «окно только что заняли»,
 * «время уже прошло» и «для выбранных услуг не хватает времени подряд»
 * приходят одним 409, а сказать их надо разными словами: в первом случае
 * помогает обновление страницы, во втором — другое окно, в третьем — другой
 * набор услуг.
 *
 * Фраза в `message` остаётся: это то, что увидит разработчик в логах и в
 * ответе API. Мастер её не видит никогда — кабинет показывает свой перевод по
 * коду, а незнакомый код сводит к общей фразе (`describeApiError` на вебе).
 */
export const DASHBOARD_ERROR_CODES = {
  /* ── Окна ────────────────────────────────────────────────────────────── */
  /** Время уже прошло: опубликовать, перенести или записать в него нельзя. */
  slotInPast: 'slot_in_past',
  /** Окно на это время у мастера уже открыто. */
  slotDuplicate: 'slot_duplicate',
  /** Окна с таким id нет — скорее всего, его только что сняли. */
  slotNotFound: 'slot_not_found',
  /** Окно занято записью: снять или перенести его можно только после отмены. */
  slotBooked: 'slot_booked',
  /** Гонка: пока страница лежала открытой, окно заняли. */
  slotJustTaken: 'slot_just_taken',
  /** Массовая публикация: весь выбранный период уже в прошлом. */
  slotsAllPast: 'slots_all_past',

  /* ── Записи ──────────────────────────────────────────────────────────── */
  /** Между окнами не хватает непрерывного времени под выбранные услуги. */
  notEnoughTime: 'not_enough_time',
  /** В корзине нет ни одной услуги. */
  noServices: 'no_services',
  /** Записи с таким id нет. */
  bookingNotFound: 'booking_not_found',
  /**
   * Запись уже завершена или отменена — править её нельзя.
   *
   * Не «не найдена»: запись есть, и мастер её видит. У завершённой цены в
   * позициях уже посчитаны как доход, у отменённой окна отданы и могли быть
   * проданы — обе заводятся заново, а не правятся.
   */
  bookingNotEditable: 'booking_not_editable',

  /* ── Каталог и клиенты ───────────────────────────────────────────────── */
  serviceNotFound: 'service_not_found',
  categoryNotFound: 'category_not_found',
  clientNotFound: 'client_not_found',
  /** Клиент с этим номером уже есть в адресной книге. */
  clientPhoneTaken: 'client_phone_taken',
} as const;

export type DashboardErrorCode = (typeof DASHBOARD_ERROR_CODES)[keyof typeof DASHBOARD_ERROR_CODES];

export function isDashboardErrorCode(value: unknown): value is DashboardErrorCode {
  return (
    typeof value === 'string' && (Object.values(DASHBOARD_ERROR_CODES) as string[]).includes(value)
  );
}
