import type { NextConfig } from 'next';

/**
 * Заголовки безопасности для того, что браузер действительно открывает.
 *
 * helmet стоит на API (apps/api/src/main.ts), но API отдаёт JSON, который
 * никто не рендерит. Кабинет, студия и публичные страницы мастеров живут
 * здесь — и до сих пор уезжали в браузер вовсе без защитных заголовков.
 *
 * CSP сюда намеренно не входит: политика, написанная наспех, ломает страницу
 * молча и в проде: у студии свой фрейм, у публичных миров — свои шрифты и
 * фоновые изображения из хранилища. Она заслуживает отдельного прохода с
 * проверкой всех шести миров, а не строки, дописанной за компанию.
 */
const securityHeaders = [
  /*
   * `SAMEORIGIN`, а не `DENY`: студия показывает страницу мастера во фрейме
   * того же origin (`/[slug]/studio-preview`), и `DENY` погасил бы холст
   * предпросмотра — он запрещает встраивание даже самому себе.
   */
  { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  /*
   * Полный адрес уходит только внутри своего origin. Наружу — одна схема с
   * доменом: публичная страница мастера часто открывается по ссылке из
   * соцсети, и адрес её кабинета в реферере чужому сайту не нужен.
   */
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  /*
   * Год HSTS с поддоменами: у каждого мастера свой поддомен
   * (ARCHITECTURE.md §3), и оставить их вне политики значит оставить
   * открытым ровно тот адрес, по которому к мастеру приходят клиенты.
   * Браузер применяет это только по HTTPS, поэтому локальной разработке
   * заголовок не мешает.
   */
  { key: 'Strict-Transport-Security', value: 'max-age=31536000; includeSubDomains' },
  /* Ничего из этого продукт не запрашивает; выключено явно, а не по умолчанию. */
  {
    key: 'Permissions-Policy',
    value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
  },
];

const nextConfig: NextConfig = {
  /*
   * Оптимизатор изображений.
   *
   * Фотографии лендинга — самое тяжёлое, что приезжает на первый экран, и
   * приезжали они исходными JPEG. AVIF и WebP снимают с них порядок величины
   * (ночной кадр: 301 КБ → 22 КБ) без видимой разницы на глаз, потому что
   * кадры тёмные и почти без резких границ.
   *
   * `qualities` перечислен явно: с Next 16 оптимизатор принимает только
   * заранее объявленные значения, иначе отвечает 400. 75 — общий случай;
   * 82 — снимки интерфейса, которые ложатся текстурой на стекло устройства,
   * там текст мелкий и артефакты сжатия видны сразу.
   */
  images: {
    /*
     * Картинки мастеров — через оптимизатор, а не как есть.
     *
     * Фон публичной страницы это её LCP-элемент, и приезжал он исходным
     * файлом: мастер грузит фотографию с телефона, то есть 3–5 МБ JPEG, и они
     * целиком уходили на первый экран клиенту в мобильной сети. Оптимизатор
     * их не трогал по простой причине — удалённые хосты не были объявлены
     * вовсе, и `next/image` на такой адрес падает; отсюда и `<img>` с
     * отключённым правилом линтера по всему продукту.
     *
     * Хост шаблоном, а не точным именем: адрес хранилища — это
     * `<project-ref>.supabase.co`, он свой у каждого окружения, и точное имя
     * здесь означало бы сломанные картинки в проде при первой же смене
     * проекта. Путь при этом сужен до публичного хранилища: оптимизатор не
     * должен работать открытым прокси к чему угодно на этом домене.
     */
    remotePatterns: [
      {
        protocol: 'https',
        hostname: '**.supabase.co',
        pathname: '/storage/v1/object/public/**',
      },
    ],
    formats: ['image/avif', 'image/webp'],
    qualities: [75, 82],
    /* Год: файлы в /public неизменяемы и меняются только вместе со сборкой. */
    minimumCacheTTL: 31_536_000,
  },
  /*
   * `Vary: Accept-Language, Cookie` здесь пробовали и убрали — не потому, что
   * передумали, а потому, что заголовок отсюда до ответа не доезжает: App
   * Router выставляет `Vary` сам (`rsc, next-router-state-tree, …`) и
   * переписывает объявленный в конфиге целиком. Проверено на прод-сборке.
   *
   * Ставить его посредником (`proxy.ts`) ради этого не стали: у охраны
   * матчер на три закрытых раздела, и расширение его на публичные адреса —
   * правка в файле, где ошибка стоит открытого кабинета.
   *
   * Корректности это не касается: лендинг и юридические тексты уходят с
   * `Cache-Control: private, no-cache, no-store` — они читают куку и потому
   * динамические, — и общего кеша, который мог бы отдать следующему
   * посетителю чужой язык, между нами и читателем нет вовсе.
   */
  async headers() {
    return [{ source: '/:path*', headers: securityHeaders }];
  },
};

export default nextConfig;
