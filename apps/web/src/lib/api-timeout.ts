/**
 * Сколько веб ждёт ответа API, прежде чем перестать ждать.
 *
 * Предела не было ни у одного запроса продукта: `fetch` ждёт столько, сколько
 * живёт соединение, и «Сохраняем…» оставалось на кнопке до закрытия вкладки.
 * Так выглядит метро, спящее радио телефона и любой сбой, при котором ответ не
 * приходит и не отказывает.
 *
 * Пределов два, и разница между ними намеренная. У серверного хопа время
 * выходит первым — он успевает ответить `504`, настоящий ответ, который
 * кабинет умеет назвать словами. Браузерный остаётся страховкой на случай,
 * когда молчит сам веб, и потому больше.
 *
 * Двадцати секунд хватает с запасом: у машин API `auto_stop_machines = "off"`
 * и минимум одна живая (`fly.toml`), то есть холодного старта, ради которого
 * стоило бы ждать дольше, нет.
 */
export const API_TIMEOUT_MS = 20_000;

/** Предел браузера. Больше серверного — см. абзац выше. */
export const CLIENT_TIMEOUT_MS = 25_000;

/**
 * Сигнал отмены по времени, не отменяющий отмену вызывающего.
 *
 * У запроса может быть свой сигнал — React Query снимает устаревшие запросы,
 * — и подменять его временем значит терять эту отмену. Побеждает тот предел,
 * который наступит раньше.
 */
export function withTimeout(signal: AbortSignal | null | undefined, ms: number): AbortSignal {
  const timeout = AbortSignal.timeout(ms);
  return signal ? AbortSignal.any([signal, timeout]) : timeout;
}

/**
 * Это отмена по времени, а не отмена вызывающим кодом?
 *
 * Первую показывают человеку, вторую он сделал сам, и объяснять её нечего.
 */
export function isTimeoutAbort(error: unknown): boolean {
  return error instanceof DOMException && error.name === 'TimeoutError';
}
