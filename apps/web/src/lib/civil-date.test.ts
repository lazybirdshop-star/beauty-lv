import { describe, expect, it } from 'vitest';

import {
  addDaysToKey,
  civilToInstant,
  keysInRange,
  mondayOfKey,
  noonOf,
  weekdayIndex,
} from './civil-date';

/**
 * Гражданские сутки не зависят ни от пояса процесса, ни от перевода стрелок.
 * Все проверки задают пояс явно — TZ прогона у разработчика и в CI разные, и
 * тест, читающий пояс среды, был бы то зелёным, то красным сам по себе.
 */

const RIGA = 'Europe/Riga';

describe('civilToInstant — гражданское время в момент', () => {
  it('летом Рига опережает UTC на три часа', () => {
    // 16 августа 2026, 10:00 в салоне — это 07:00 UTC.
    expect(civilToInstant('2026-08-16', 10 * 60, RIGA).toISOString()).toBe(
      '2026-08-16T07:00:00.000Z',
    );
  });

  it('зимой — на два: смещение берётся на сам момент, а не на «сейчас»', () => {
    // 16 января 2026, те же 10:00 в салоне — уже 08:00 UTC.
    expect(civilToInstant('2026-01-16', 10 * 60, RIGA).toISOString()).toBe(
      '2026-01-16T08:00:00.000Z',
    );
  });

  it('переживает саму ночь перевода стрелок', () => {
    // Осенний перевод в ЕС — последнее воскресенье октября, 04:00 → 03:00 по Риге.
    // 10:00 этого дня уже в зимнем смещении.
    expect(civilToInstant('2026-10-25', 10 * 60, RIGA).toISOString()).toBe(
      '2026-10-25T08:00:00.000Z',
    );
    // А накануне — ещё в летнем.
    expect(civilToInstant('2026-10-24', 10 * 60, RIGA).toISOString()).toBe(
      '2026-10-24T07:00:00.000Z',
    );
  });

  it('полдень суток — представитель дня, который существует всегда', () => {
    expect(noonOf('2026-08-16', RIGA).toISOString()).toBe('2026-08-16T09:00:00.000Z');
  });

  it('в поясе с получасовым смещением тоже честен', () => {
    // Индия — UTC+5:30 круглый год.
    expect(civilToInstant('2026-08-16', 10 * 60, 'Asia/Kolkata').toISOString()).toBe(
      '2026-08-16T04:30:00.000Z',
    );
  });
});

describe('арифметика гражданских суток', () => {
  it('«плюс сутки» остаются сутками через перевод стрелок', () => {
    expect(addDaysToKey('2026-10-24', 1)).toBe('2026-10-25');
    expect(addDaysToKey('2026-10-25', 1)).toBe('2026-10-26');
  });

  it('переходит через границу месяца и года', () => {
    expect(addDaysToKey('2026-08-31', 1)).toBe('2026-09-01');
    expect(addDaysToKey('2026-12-31', 1)).toBe('2027-01-01');
    expect(addDaysToKey('2026-01-01', -1)).toBe('2025-12-31');
  });

  it('знает високосный февраль', () => {
    expect(addDaysToKey('2028-02-28', 1)).toBe('2028-02-29');
    expect(addDaysToKey('2026-02-28', 1)).toBe('2026-03-01');
  });

  it('неделя начинается с понедельника', () => {
    // 2026-08-16 — воскресенье.
    expect(weekdayIndex('2026-08-16')).toBe(6);
    expect(mondayOfKey('2026-08-16')).toBe('2026-08-10');
    expect(mondayOfKey('2026-08-10')).toBe('2026-08-10');
  });

  it('промежуток дат включает оба конца и не растёт бесконечно', () => {
    expect(keysInRange('2026-08-14', '2026-08-16')).toEqual([
      '2026-08-14',
      '2026-08-15',
      '2026-08-16',
    ]);
    expect(keysInRange('2026-08-16', '2026-08-14')).toEqual([]);
    expect(keysInRange('2026-01-01', '2030-01-01')).toHaveLength(92);
  });
});
