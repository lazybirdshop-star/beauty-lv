/**
 * Куда вернуть человека после входа.
 *
 * Охрана, разворачивая гостя с закрытого адреса, кладёт этот адрес в `next`
 * (`proxy.ts`), но экран входа параметр не читал и уводил на `?? '/'` — то
 * есть на лендинг. Больнее всего это в установленной панели: иконка открывает
 * `/admin`, протухшая сессия отправляет на вход, и вместо очереди заявок
 * администратор оказывался на витрине продукта.
 *
 * `next` принимается только внутри той области, которую сервер и так назвал
 * домом этого пользователя (`redirectUrl` из `POST /api/auth/login`). Так
 * возвращается ровно та страница, с которой человека развернули, и при этом
 * чужой адрес в параметре не может отправить его туда, откуда охрана
 * немедленно развернёт снова. Заодно это отсекает `//evil.example` и
 * абсолютные ссылки: они не начинаются с домашней области.
 */
export function returnTarget(requestedNext: string | null, redirectUrl: string | null): string {
  const home = redirectUrl ?? '/';

  if (!redirectUrl || !requestedNext) return home;
  if (!requestedNext.startsWith('/') || requestedNext.startsWith('//')) return home;

  /* Сравнивается только путь: у `next` может быть хвост из query, и он едет
     обратно вместе с адресом, но решение о допуске принимает не он. */
  const path = requestedNext.split(/[?#]/)[0] ?? '';

  return path === redirectUrl || path.startsWith(`${redirectUrl}/`) ? requestedNext : home;
}
