/**
 * Адрес посетителя, каким его можно предъявить API.
 *
 * Хоп BFF → API подписан `INTERNAL_PROXY_SECRET`, и под этой подписью API
 * верит присланному адресу как своему (см. `ClientThrottlerGuard`). Значит
 * пересылать сюда `x-forwarded-for` как есть нельзя: заголовок пришёл из
 * браузера, и если платформа к нему **дописывает** реальный адрес, а не
 * заменяет его, то первый элемент цепочки выбирает сам вызывающий — циклом
 * `for` со сменой строки он обнуляет счётчики входа, регистрации,
 * восстановления доступа и гостевой записи. Ровно та щель, ради закрытия
 * которой подпись и вводилась.
 *
 * Поэтому наружу уходит не цепочка, а один адрес, выбранный здесь:
 *
 * 1. `x-real-ip` — его ставит платформа и клиент перезаписать его не может;
 * 2. иначе **последний** элемент `x-forwarded-for` — его дописывает ближайший
 *    доверенный прокси, тогда как первые элементы мог сочинить вызывающий.
 *
 * Возврат `null` означает «адреса нет»: заголовок тогда не ставится вовсе, и
 * API считает запрос по адресу самого BFF — грубее, но честно.
 */
export function clientAddress(headers: Headers): string | null {
  const real = headers.get('x-real-ip')?.trim();
  if (real) return real;

  const chain = headers.get('x-forwarded-for');
  if (!chain) return null;

  const hops = chain
    .split(',')
    .map((hop) => hop.trim())
    .filter(Boolean);

  return hops.at(-1) ?? null;
}
