import { describe, expect, it } from 'vitest';

import { toCsv } from './csv';

/**
 * CSV собирается из свободного текста, который писали не мы: имя гостя и
 * заметку мастера. Поэтому здесь проверяется не «работает ли join», а два
 * свойства, которые ломают чужой файл или чужую машину, — экранирование и
 * формулы.
 */

interface Row {
  name: string;
  note: string;
}

const columns = [
  { header: 'Имя', value: (row: Row) => row.name },
  { header: 'Заметка', value: (row: Row) => row.note },
];

describe('toCsv — экранирование', () => {
  it('заголовок идёт первой строкой', () => {
    expect(toCsv<Row>([], columns)).toBe('Имя,Заметка');
  });

  it('строки разделены CRLF — иначе Excel читает файл одной строкой', () => {
    const csv = toCsv([{ name: 'Анна', note: '' }], columns);

    expect(csv).toBe('Имя,Заметка\r\nАнна,');
  });

  it('запятая в тексте не разъезжает строку', () => {
    // Заметка мастера — свободный текст, и запятая в ней обычное дело.
    const csv = toCsv([{ name: 'Анна', note: 'красит в два тона, аллергия' }], columns);

    expect(csv).toContain('"красит в два тона, аллергия"');
  });

  it('кавычка внутри поля удваивается', () => {
    const csv = toCsv([{ name: 'Анна', note: 'просила «как в тот раз"' }], columns);

    expect(csv).toContain('"просила «как в тот раз"""');
  });

  it('дефис в начале заметки не делает её формулой', () => {
    // «-красит сама» начинается с тире: для Excel это выражение.
    const csv = toCsv([{ name: 'Анна', note: '-красит сама' }], columns);

    expect(csv).toContain(`'-красит сама`);
  });

  it('перевод строки внутри заметки остаётся внутри поля', () => {
    const csv = toCsv([{ name: 'Анна', note: 'первая строка\nвторая' }], columns);

    expect(csv).toContain('"первая строка\nвторая"');
  });

  it('пустое и отсутствующее — пустое поле, а не «undefined»', () => {
    const csv = toCsv(
      [{ name: '', note: '' }],
      [
        { header: 'Имя', value: (row: Row) => row.name },
        { header: 'Телефон', value: () => null },
      ],
    );

    expect(csv).toBe('Имя,Телефон\r\n,');
  });
});

/**
 * Excel и Google Sheets исполняют ячейку, начинающуюся с `=`, `+`, `-` или
 * `@`. Имя гостя приходит с публичной страницы, то есть от кого угодно, — и
 * без этой защиты выгрузка адресной книги означала бы исполнение чужого кода
 * в таблице мастера.
 */
describe('toCsv — формулы обезвреживаются', () => {
  it.each(['+1+1', '-1+1', '@SUM(A1)', '=A1*2'])(
    'значение «%s» становится текстом',
    (dangerous) => {
      const csv = toCsv([{ name: dangerous, note: '' }], columns);

      /* Апостроф перед значением; сам редактор его не показывает. Кавычек
         здесь нет и не нужно — в этих значениях нет ни разделителя, ни
         кавычки, ни перевода строки, а лишние кавычки только шумели бы. */
      expect(csv).toContain(`'${dangerous}`);
    },
  );

  it('формула с запятой и кавычками получает и апостроф, и кавычки', () => {
    const csv = toCsv([{ name: '=HYPERLINK("http://evil","клик")', note: '' }], columns);

    // Обе защиты независимы и складываются.
    expect(csv).toContain(`"'=HYPERLINK(""http://evil"",""клик"")"`);
  });

  it('обычное имя апострофом не портится', () => {
    const csv = toCsv([{ name: 'Анна', note: '' }], columns);

    expect(csv).toContain('Анна');
    expect(csv).not.toContain("'Анна");
  });

  it('телефон с плюсом — не формула и остаётся как есть', () => {
    /* `+371…` начинается с плюса, но это номер, а не выражение: он всё равно
       обезвреживается — иначе Excel посчитает его как сложение и покажет
       число. Апостроф здесь сохраняет номер читаемым. */
    const csv = toCsv([{ name: '+37120000111', note: '' }], columns);

    expect(csv).toContain(`'+37120000111`);
  });
});
