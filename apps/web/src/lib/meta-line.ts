/**
 * Строка фактов через точку-разделитель: «Педикюр · Maija · 40 €».
 *
 * Разделитель приклеен к предыдущему слову неразрывным пробелом. Обычный
 * пробел позволял переносу встать перед точкой, и новая строка начиналась с
 * «· Maija» — висящий знак читался опечаткой (критика 2026-09-25, находка
 * нескольких прогонов). После точки пробел обычный: там перенос уместен.
 *
 * Пустые части выбрасываются: строка фактов не должна начинаться с
 * разделителя, если первого факта не случилось.
 */
export function metaLine(...parts: (string | number | false | null | undefined)[]): string {
  return parts
    .filter(
      (part): part is string | number =>
        part !== null && part !== undefined && part !== '' && part !== false,
    )
    .map(String)
    .join(' · ');
}

/**
 * Тот же разделитель для мест, где части склеивает `join`, а не вызов
 * функции: неразрывный пробел перед точкой, обычный после.
 */
export const META_SEPARATOR = ' · ';
