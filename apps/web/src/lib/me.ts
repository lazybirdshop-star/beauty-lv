import { cache } from 'react';

import { serverApiFetch } from '@/lib/server-api';

/** Что кабинету нужно знать о вошедшем до первого кадра. */
export interface Me {
  fullName?: string;
  locale?: string;
}

/**
 * Строка вошедшего — один запрос `/auth/me` на один проход отрисовки.
 *
 * `cache()` склеивает вызовы одной функции, но не две разные: имя для угла
 * панели и язык для словаря спрашивались отдельными обёртками, и каждая
 * навигация по кабинету стоила двух сетевых хопов Vercel → Fly, а на той
 * стороне — двух проходов `JwtAuthGuard`, который по документированному
 * размену перечитывает строку пользователя из базы на каждом запросе.
 * Поэтому запрос живёт здесь один, а `currentUserName` и `getRequestLocale`
 * читают из него.
 *
 * `null` вместо ошибки: у обоих потребителей есть осмысленное умолчание, а
 * панель, упавшая из-за имени в углу, не работает вовсе. Кто именно уводит
 * на вход, решает охрана, а не эта функция.
 */
export const me = cache(async (): Promise<Me | null> => {
  try {
    const { user } = await serverApiFetch<{ user?: Me }>('/auth/me');
    return user ?? null;
  } catch {
    return null;
  }
});
