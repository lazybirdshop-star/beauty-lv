'use client';

import { useCallback, useSyncExternalStore } from 'react';

/**
 * Текущий момент как внешний источник, а не как `Date.now()` посреди разметки.
 *
 * Часы — единственное, что меняется само, без действий мастера и без новых
 * данных с сервера. Спрошенные прямо в рендере, они делают его нечистым: тот
 * же компонент с теми же свойствами рисуется по-разному на сервере и в
 * браузере, и React объявляет расхождение разметки.
 *
 * `useSyncExternalStore` — ровно тот примитив, который для этого и заведён:
 * на сервере и в первом кадре гидратации он отдаёт `null` («ещё не знаем»), а
 * дальше живёт по часам браузера. Экран, который решает по времени, обязан
 * уметь сказать «пока не знаю» и не показывать в этот миг действие, которое
 * может оказаться недопустимым, — это одна лишняя ветка на месте вызова и ни
 * одной неправильно показанной кнопки.
 *
 * Снимок округляется до шага: `getSnapshot` обязан возвращать одно и то же
 * значение, пока источник не изменился, иначе React перерисовывал бы экран
 * бесконечно. Округление же задаёт и точность — минута. Всё, что кабинет
 * решает по времени, — это границы визитов и суток, и секунды там ничего не
 * меняют.
 */
export function useNow(intervalMs = 60_000): number | null {
  const subscribe = useCallback(
    (onChange: () => void) => {
      const timer = setInterval(onChange, intervalMs);
      return () => clearInterval(timer);
    },
    [intervalMs],
  );

  return useSyncExternalStore(
    subscribe,
    () => Math.floor(Date.now() / intervalMs) * intervalMs,
    () => null,
  );
}
