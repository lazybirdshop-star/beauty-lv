import { ApiError } from './api-error';

/**
 * Сессия кончилась, пока вкладка была открыта.
 *
 * Токен живёт двенадцать часов, обновляющего рядом нет, а охрана (`proxy.ts`)
 * разворачивает только переходы по страницам — вкладку, оставленную со
 * вчера, не разворачивает никто. Каждое сохранение в ней получало `401` и,
 * до этой правки, молчало: кнопка выходила из «Сохраняем…» и не говорила
 * ничего. Так выглядело утро после вечера, и лечилось это обновлением
 * страницы, до которого надо было додуматься.
 *
 * Именно `401`, и никогда `403`: второй означает «вошли, но сюда нельзя» —
 * человек в системе, и выкидывать его на вход значит терять его работу за
 * чужую ошибку прав.
 */
export function isSessionExpired(error: unknown): boolean {
  return error instanceof ApiError && error.status === 401;
}

/**
 * Адрес входа, помнящий, откуда человека увели.
 *
 * `next` читает экран входа (`returnTarget`), и он же сверяет адрес с домом
 * пользователя — сюда попадает собственный путь вкладки, поэтому подделать
 * его может только тот, кто и так им управляет.
 */
export function loginUrlFor(pathWithQuery: string): string {
  return `/login?next=${encodeURIComponent(pathWithQuery)}`;
}
