/**
 * Кружок с инициалами — то, что стоит вместо фотографии во всех таблицах
 * макета.
 *
 * Одна функция на весь кабинет: до этого она была скопирована в пяти файлах, и
 * шестая копия отличалась запасной буквой. Инициалы — часть того, как человек
 * узнаёт строку, и расходиться между экранами они не имеют права.
 */
export function initials(name: string, fallback = '?'): string {
  return (
    name
      .trim()
      .split(/\s+/)
      .filter(Boolean)
      .slice(0, 2)
      .map((part) => part[0]?.toUpperCase() ?? '')
      .join('') || fallback
  );
}

/** Тонов шесть: больше — и они перестают различаться с одного взгляда. */
const TONES = 6;

/**
 * Тон человека — один и тот же во всём кабинете (прототип «Кабинет 2026»).
 *
 * Прежде подложка инициалов была одним нейтральным тоном: по правилу 02
 * Design System V2 цвет принадлежал услуге. В салоне это значило, что на
 * ленте дня, в колонке команды и в ряду ведомости четверо различались только
 * подписью, — то есть их надо было читать, а не видеть.
 *
 * Владелец принял облик прототипа, где цвет принадлежит человеку, а услуга
 * помечена точкой у названия. Двух цветовых систем на одном блоке не бывает:
 * если человек цветной, услуга — точка.
 *
 * Тон считается из идентификатора: постоянный у одного человека и разный у
 * соседних. Возвращаются токены, а не hex, — тёмная тема берёт своё.
 */
export function memberTone(seed: string): number {
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  return (hash % TONES) + 1;
}

/**
 * Тона команды — все разные, сколько бы ни совпал хеш.
 *
 * Сам по себе `memberTone` иногда выдаёт двоим одно и то же: шесть тонов на
 * произвольные идентификаторы. На общей ленте дня и в колонках календаря это
 * означает двух мастеров одного цвета — ровно ту беду, ради которой тон и
 * заведён. Здесь хеш остаётся первым предложением, а занятый тон уступает
 * место следующему свободному. Порядок берётся из списка команды, поэтому у
 * одного состава распределение постоянно.
 *
 * Больше шести человек — тона начинают повторяться снова: седьмому цвета
 * взять неоткуда, и врать о его уникальности хуже, чем повторить.
 */
export function teamTones(memberIds: string[]): Record<string, number> {
  const taken = new Set<number>();
  const tones: Record<string, number> = {};

  for (const id of memberIds) {
    const wanted = memberTone(id);
    let tone = wanted;
    for (let step = 1; taken.has(tone) && step < TONES; step += 1) {
      tone = ((wanted - 1 + step) % TONES) + 1;
    }
    taken.add(tone);
    tones[id] = tone;
    if (taken.size === TONES) taken.clear();
  }

  return tones;
}

export function avatarTint(seed: string): { background: string; color: string } {
  const tone = memberTone(seed);
  return { background: `var(--tone-${tone}-soft)`, color: `var(--tone-${tone}-ink)` };
}
