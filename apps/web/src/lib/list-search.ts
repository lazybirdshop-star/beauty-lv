/**
 * С какой длины списка на экране появляется поиск.
 *
 * Ниже этого числа всё умещается на экран-другой, и поле поиска — мебель:
 * лишний элемент управления над списком, который и так виден целиком.
 *
 * Общее для записей и клиентов намеренно. Число было объявлено дважды, в двух
 * фичах, с одинаковым обоснованием — а значит, при следующей правке разъехалось
 * бы, и два списка кабинета начали бы отращивать поиск в разные моменты без
 * всякой причины.
 */
export const SEARCH_THRESHOLD = 8;

/**
 * Цифры номера — для **поиска** по обрывку, а не для сравнения людей.
 *
 * Намеренно не `phoneMatchKey`: тот отвечает на вопрос «тот же ли это человек»
 * и оставляет восемь последних цифр, поэтому запрос «371» не нашёл бы ни
 * одного латвийского номера. Поиск — противоположная задача: мастер набирает
 * любой кусок номера, какой помнит, и ждёт совпадения по подстроке.
 */
export function searchableDigits(value: string | null | undefined): string {
  return (value ?? '').replace(/\D/g, '');
}
