/**
 * Цвет метки услуги.
 *
 * В артбордах у каждой услуги свой приглушённый тон — точка перед названием в
 * линейке дня, в календаре и в списке записей. Настоящая услуга своего цвета в
 * базе не хранит, и заводить колонку ради точки в семь пикселей не за чем:
 * тон считается из идентификатора, поэтому он постоянный у одной услуги и
 * разный у соседних, а это ровно то, ради чего метка существует — отличить
 * маникюр от педикюра, не читая строку.
 *
 * Палитра из артбордов (`app-design/data.mjs`): приглушённые, ни один не
 * спорит с розовым акцентом продукта и ни один не повторяет цвета статусов —
 * зелёного, янтарного и красного, у которых в кабинете есть свой смысл.
 */
const TONES = [
  '#C8705F',
  '#8E6A9C',
  '#6E9A7A',
  '#5E8FB8',
  '#A9825C',
  '#8B7BA8',
  '#7F9C8E',
  '#B0708A',
] as const;

export function serviceTone(id: string): string {
  let hash = 0;
  for (let i = 0; i < id.length; i += 1) {
    hash = (hash * 31 + id.charCodeAt(i)) >>> 0;
  }
  return TONES[hash % TONES.length]!;
}
