/** Ровно то, что браузер кладёт в `PushSubscription.toJSON()`, разложенное по полям. */
export interface PushSubscriptionPayload {
  endpoint: string;
  p256dh: string;
  auth: string;
  userAgent?: string;
}

/**
 * Что кабинет показывает мастеру. Состояний больше, чем «включено/выключено»,
 * потому что причин, по которым уведомление не придёт, тоже больше — и каждая
 * требует своих слов и своей кнопки.
 */
export type PushState =
  /** Ещё выясняем: спросили сервер про ключ, спросили браузер про подписку. */
  | 'checking'
  /** Уведомления в этой установке продукта не настроены — у сервера нет ключей. */
  | 'unavailable'
  /** Браузер не умеет push. */
  | 'unsupported'
  /** Safari на iPhone: умеет, но только для приложения на экране «Домой». */
  | 'needs-install'
  /** Мастер отказала в разрешении — включить обратно можно только в настройках браузера. */
  | 'denied'
  | 'off'
  | 'on';
