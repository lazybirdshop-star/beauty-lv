import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

const WORLDS = ['aura', 'funk', 'luxury', 'minimal', 'poster', 'soft'];

/**
 * Проверка исходником, а не поведением, — потому что поведение здесь не
 * воспроизводится в jsdom.
 *
 * Кнопка подвала шторки одна на все шаги: React переиспользует один и тот же
 * DOM-узел и лишь меняет ему атрибуты. Пока она была `type="submit"`, нажатие
 * «дальше» на шаге времени успевало превратить её в кнопку отправки до того,
 * как браузер выполнял действие по умолчанию того же нажатия, — и один тап и
 * переходил к контактам, и отправлял запись. С подставленными данными
 * вошедшего человека это записывало мгновенно, не дав ничего проверить.
 *
 * jsdom действие по умолчанию нажатия не исполняет вовсе, поэтому тест,
 * притворяющийся браузером, прошёл бы и на сломанном коде. Инвариант же
 * формулируется одной строкой: подвал не отправляет форму нативно, он просит
 * её отправиться (`submitBookingForm`).
 */
describe('подвал шторки записи', () => {
  it.each(WORLDS)('мир %s не отправляет форму нативной кнопкой', (world) => {
    const source = readFileSync(
      join(__dirname, '..', 'compositions', world, 'booking-sheet.tsx'),
      'utf8',
    );

    expect(source).not.toContain('type="submit"');
    expect(source).toContain('submitBookingForm');
  });
});
