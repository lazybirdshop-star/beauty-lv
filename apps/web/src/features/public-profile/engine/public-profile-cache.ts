/**
 * Кэш публичной страницы мастера — имя метки и срок жизни.
 *
 * Отдельный модуль от `revalidate.ts` не по вкусу, а по правилу: файл с
 * `'use server'` вправе экспортировать только асинхронные функции — всё
 * остальное в нём становится не экспортом, а ошибкой сборки. Константа и
 * помощник нужны обеим сторонам, поэтому живут здесь, где их читает и
 * страница, и действие.
 */

/**
 * Сколько публичная страница имеет право быть несвежей.
 *
 * Пять минут — не компромисс между «быстро» и «правильно», а срок, за который
 * мастер физически не успевает удивиться. Всё, что она меняет из Студии и
 * настроек, гасит кэш немедленно (`revalidatePublicProfile`); этот срок
 * страхует то, чего мы позвать не можем: правку из другой вкладки, из панели
 * администратора, из будущего экрана, который забудут сюда подключить.
 */
export const PUBLIC_PROFILE_REVALIDATE_SECONDS = 300;

/** Метка кэша одной публичной страницы. По ней же её и гасят. */
export function publicProfileTag(slug: string): string {
  return `public-profile:${slug}`;
}
