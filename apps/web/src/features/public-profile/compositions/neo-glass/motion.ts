import type { MotionSpec } from '../../contracts/chrome';

/**
 * Пружины мира для motion/react (§10.4: пружины — только через уже
 * стоящую в стеке библиотеку, никаких самодельных rAF-циклов).
 *
 * Пружина считается там, где кривой её не выразить: перетекание пилюли
 * навигации между двумя произвольными позициями. Всё остальное движение
 * мира — входы, шторка, ячейки, нажатия — играет CSS-фолбэком пружины
 * `--ease-style` (`cubic-bezier(0.34, 1.3, 0.5, 1)`), потому что фолбэк
 * стоит ноль килобайт JS и, главное, работает на первом кадре SSR-выдачи,
 * до гидрации.
 */
export const SPRINGS = {
  /** Панель: мягкий перелёт ≤ 2% — стеклянный лист влетает и садится. */
  panel: { type: 'spring', stiffness: 260, damping: 26 },
  /** Контрол: быстрый ответ почти без перелёта. */
  press: { type: 'spring', stiffness: 400, damping: 30 },
} as const;

/**
 * Хореография Neo Glass как данные (§10). Вход и выход шторки —
 * токенизированные продуктовые keyframes (`sheet-panel-in/out`), но
 * значения токенов у этого мира свои: взлёт на 64px с `scale(0.94) → 1` за
 * 480ms по пружинной кривой, уход за 240ms; гашение — 45% черни плюс
 * статичный blur 8px, единственный в коллекции. Сцены сменяются
 * пространственно: месяц календаря и шаги записи приходят направленным
 * сдвигом на 24px, а не растворяются друг в друге.
 */
export const motion: MotionSpec = {
  sheetInClass: 'sheet-panel-in',
  sheetOutClass: 'sheet-panel-out',
  stepTransition: 'spatial',
  springs: {
    sheet: SPRINGS.panel,
    press: { scale: 0.96, duration: 220 },
    reveal: { y: 16, stagger: 45 },
  },
};
