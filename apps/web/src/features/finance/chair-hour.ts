/**
 * Цена часа кресла: сколько приносит час занятого времени.
 *
 * Сумма за период отвечает «сколько заработано», средний чек — «сколько
 * приносит визит». Ни то, ни другое не говорит, дорого ли стоит само время:
 * час стрижек и час окрашивания приносят разное, и понять это по сумме
 * нельзя. Цена часа кресла сравнивает услуги и периоды на одной мере.
 *
 * Считается по завершённым визитам: минуты, которые кресло действительно
 * было занято. Пустой период возвращает `null` — делить не на что, а ноль
 * здесь означал бы «час кресла не стоит ничего».
 */
export function chairHourRate(
  totalRevenue: number,
  rows: readonly { minutes: number }[],
): number | null {
  const minutes = rows.reduce((sum, row) => sum + Math.max(0, row.minutes), 0);
  if (minutes <= 0) return null;
  return Math.round(totalRevenue / (minutes / 60));
}
