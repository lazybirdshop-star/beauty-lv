import type { PublishedSlot } from './types';

/**
 * Окна, в которые ещё можно кого-то записать.
 *
 * Свободного статуса мало: окно, опубликованное на прошлой неделе и никем не
 * занятое, остаётся `available` навсегда. Шторка «Новая запись» показывала их
 * все — восемь дней прошлого впереди списка, и первое из них выбиралось
 * само, — а отказ приходил только с сервера, после заполненной формы.
 *
 * Сервер это по-прежнему проверяет вторым свидетелем (`bookings.repository`),
 * и это правильно: между показом списка и нажатием кнопки может пройти сколько
 * угодно времени, пока страница лежит открытой во вкладке. Но первый ответ на
 * вопрос «куда можно встать» обязан быть здесь — иначе интерфейс предлагает
 * то, чего не может сделать.
 *
 * `now` — аргумент, а не `Date.now()` внутри: серверный компонент и клиент
 * должны иметь возможность спросить об одном и том же моменте, и тест не
 * должен зависеть от часов машины.
 */
export function bookableSlots(slots: PublishedSlot[], now: Date = new Date()): PublishedSlot[] {
  const from = now.getTime();
  return slots.filter(
    (slot) => slot.status === 'available' && new Date(slot.startsAt).getTime() >= from,
  );
}
