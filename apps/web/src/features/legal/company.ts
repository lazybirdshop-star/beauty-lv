/**
 * Дата последней редакции юридических текстов.
 *
 * Одна на все документы и все языки: переводы одной редакции обязаны быть
 * датированы одинаково, иначе читатель не поймёт, какая версия свежее.
 * Меняется руками при правке любого документа — это заявление о том, что
 * редакция новая, а не отметка времени сборки.
 */
export const LEGAL_REVISION = '2026-08-25';

/**
 * Реквизиты одной строкой — или `null`, если заполнять пока нечего.
 *
 * Возвращает `null`, а не пустую строку: вызывающий обязан решить, что делать
 * с отсутствием реквизитов, и не может случайно напечатать пустой абзац.
 */
export function formatRegistration(entity: LegalEntity, countryName: string): string | null {
  const parts = [entity.legalName, entity.registrationNumber, entity.address, countryName].filter(
    (part): part is string => Boolean(part),
  );

  // Одна лишь страна реквизитами не является.
  return parts.length > 1 ? parts.join(', ') : null;
}
