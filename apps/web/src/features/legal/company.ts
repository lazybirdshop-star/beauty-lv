/**
 * Реквизиты оператора — единственный источник правды для юридических текстов,
 * подвала лендинга и служебных писем.
 *
 * Вынесено в отдельный модуль намеренно: одно и то же наименование и один и
 * тот же адрес обязаны совпадать в политике конфиденциальности, в условиях
 * использования и в уведомлении о cookie. Три копии одной строки рано или
 * поздно разъезжаются, а разъехавшиеся реквизиты в политике — это не опечатка,
 * а несоответствие статье 13 GDPR.
 *
 * ── ЗАПОЛНИТЬ ПЕРЕД ПУБЛИКАЦИЕЙ ──────────────────────────────────────────
 * Поля `legalName`, `registrationNumber` и `address` стоят в `null`, потому
 * что настоящих значений продукт пока не знает, а выдумывать регистрационный
 * номер нельзя: политика с несуществующим номером хуже, чем политика без него.
 * Пока они пусты, документы выпускаются от торгового имени и не печатают
 * строку реквизитов. Владелец подставляет сюда данные из выписки Реестра
 * предприятий — и тексты, подвал и письма подхватывают их разом.
 */

export type LegalEntity = {
  /** Торговое имя. Печатается везде, где нет юридического наименования. */
  readonly brand: string;
  /** Юридическое наименование по регистру. `null` — пока не подтверждено. */
  readonly legalName: string | null;
  /** Единый регистрационный номер. `null` — пока не подтверждён. */
  readonly registrationNumber: string | null;
  /** Юридический адрес одной строкой, без индекса страны. */
  readonly address: string | null;
  /** Код страны по ISO 3166-1 alpha-2. Название страны локализуют документы. */
  readonly countryCode: string;
  /** Основной домен без схемы. */
  readonly domain: string;
  /** Почтовые ящики. Разные адреса — разные обязанности и разные сроки. */
  readonly email: {
    /** Общие вопросы и поддержка. */
    readonly support: string;
    /** Запросы субъектов данных (статьи 15–22 GDPR). */
    readonly privacy: string;
    /** Договорные и претензионные вопросы. */
    readonly legal: string;
  };
};

