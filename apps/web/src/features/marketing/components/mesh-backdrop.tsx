/**
 * Градиентное поле за содержимым.
 *
 * Серверный компонент без единого байта JS: вся работа — два пустых элемента
 * и CSS (`marketing-mesh.css`), поэтому поле есть уже в первом ответе и не
 * ждёт гидратации. Растра нет сознательно — герой это LCP, и класть в него
 * полноэкранную картинку ради фона значит платить за неё первой секундой.
 *
 * Тон выбирается землёй, на которой поле лежит: `dawn` для светлой части
 * страницы, `ember` для тёмной полосы. Третьего не будет — смена земли на
 * лендинге одна, и её единственность и есть композиция.
 *
 * Поле занимает родителя целиком и своей геометрией не распоряжается:
 * сколько его и где оно кончается — решает место, которое его ставит.
 * Родитель обязан быть позиционированным.
 */

interface MeshBackdropProps {
  tone: 'dawn' | 'ember';
}

export function MeshBackdrop({ tone }: MeshBackdropProps) {
  return (
    <div aria-hidden="true" className={`lp-mesh lp-mesh--${tone}`}>
      <span className="lp-mesh__field" />
      <span className="lp-mesh__veil" />
      <span className="lp-mesh__grain" />
    </div>
  );
}
