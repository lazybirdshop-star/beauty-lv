/* AI-RULES BRK-05: короткое слово не имеет права закончить строку, а число —
   оторваться от своей единицы. Руками по трём языкам это ровно то место, где
   заводятся висячие строки, поэтому связывание происходит один раз, здесь.

   Помощник написан автором лендинга, но подключён не был — единственный пункт
   его же приёмки, оставшийся незакрытым. Подключён к абзацам: заголовки ломает
   вручную автор (BRK-04), и связывать в них нечего. */

const NBSP = '\u00A0';
const SHORT =
  'в|во|на|над|под|с|со|к|ко|у|о|об|и|а|но|из|за|по|до|от|для|при|без|же|ли|бы|не|что|как';

export function nb(text: string): string {
  return text
    .replace(
      new RegExp(`(^|[\\s(\u00ab])(${SHORT})\\s`, 'gi'),
      (_m, lead: string, word: string) => `${lead}${word}${NBSP}`,
    )
    .replace(/(\d)\s+(?=[\u0430-\u044f\u0451a-z%/\u20bd])/gi, `$1${NBSP}`);
}
