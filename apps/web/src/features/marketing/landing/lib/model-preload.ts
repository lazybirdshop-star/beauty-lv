/* Модель устройства, привезённая заранее и оставленная в памяти.

   Сцена строится с первым движением читателя, а не на загрузке страницы —
   иначе её первые кадры держат главный поток (см. mockup-stage.tsx). Но
   строить с нуля в этот момент значит заставить читателя ждать: 614 КБ по
   мобильной сети — это несколько секунд, в которые устройство на первом
   экране стоит картинкой и не отзывается на прокрутку.

   Поэтому байты модели забираются заранее — в простое, после события
   `load`, когда полоса уже никому не нужна, — и держатся готовым буфером.
   К моменту, когда читатель тронул страницу, разбирать есть что, и сцена
   поднимается без похода в сеть.

   Держать буфер, а не полагаться на кэш браузера, — намеренно: файлы из
   /public отдаются с `max-age=0, must-revalidate`, то есть второй запрос
   всё равно уходит на сервер за подтверждением. Лишний круг по сети ровно
   в тот момент, когда читатель ждёт, — это то, от чего здесь и уходим. */

let buffer: Promise<ArrayBuffer> | null = null;
let bufferUrl = '';

/**
 * Начать загрузку. Повторные вызовы для того же адреса бесплатны.
 * Ошибку не бросает: не доехало — сцена сходит в сеть сама, как раньше.
 */
export function prefetchModel(url: string): void {
  if (buffer && bufferUrl === url) return;
  bufferUrl = url;
  buffer = fetch(url, { priority: 'low' } as RequestInit)
    .then((res) => (res.ok ? res.arrayBuffer() : Promise.reject(new Error(String(res.status)))))
    .catch(() => {
      /* Забыть неудачу, чтобы сцена попробовала своим ходом. */
      buffer = null;
      bufferUrl = '';
      throw new Error('model prefetch failed');
    });
}

/** Привезённые байты, если они есть и это тот самый адрес. */
export function takeModelBuffer(url: string): Promise<ArrayBuffer> | null {
  return buffer && bufferUrl === url ? buffer : null;
}
