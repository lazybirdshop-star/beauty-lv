'use client';

import type { ReactNode } from 'react';

import { useMagnetic } from './hooks/use-magnetic';
import { useReveal } from './hooks/use-reveal';

/**
 * Единственное, ради чего лендингу нужен браузер целиком: два наблюдателя за
 * страницей — появление по скроллу и притяжение кнопки к курсору.
 *
 * Отдельной обёрткой, а не хуками в корне: `'use client'` на корне утаскивал
 * в клиентский граф все тринадцать секций, хотя шесть из них — «Возможности»,
 * «Соло», «Три шага», «Тарифы», финал и подвал — не держат ни состояния, ни
 * обработчиков. Страница маркетингового документа статична на девять десятых,
 * и оживлять её целиком браузер не обязан.
 *
 * Оба хука работают одним слушателем на документ и детей не трогают, поэтому
 * обёртка ничего не знает о том, что в неё положили: `children` приезжают уже
 * отрисованными на сервере и через клиентскую границу не проходят.
 */
export function ScrollEffects({ children }: { children: ReactNode }) {
  useReveal();
  useMagnetic();

  return <>{children}</>;
}
