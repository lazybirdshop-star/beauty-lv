/* Фотография, лежащая во весь свой слой.
   На странице их четыре — протяжка света за первым экраном, металл под
   обликами, поверхность под панелью переписки и ночной кадр, — и все четыре
   раскладываются одинаково: заполнить родителя целиком, обрезать по кадру,
   не мешать тому, что лежит поверх.

   Раньше три из них приходили из CSS (`background: url(...)`), а четвёртая —
   обычным `<img>`. Обе дороги мимо оптимизатора: браузер тянул исходные JPEG
   целиком и сразу, включая те, что лежат за три экрана вниз. Здесь они идут
   через `next/image`: AVIF/WebP вместо JPEG, размер под ширину экрана и
   отложенная загрузка для всего, что не в первом кадре.

   Слой-родитель обязан быть спозиционирован — `fill` раскладывается по нему
   абсолютно. Все четыре и так `position: absolute` или `relative`. */
import Image from 'next/image';

type PhotoProps = {
  src: string;
  /** Пусто для декораций: слой без собственного сообщения читалке не нужен. */
  alt?: string;
  className?: string;
  /** Ширина слоя на экране — из неё оптимизатор выбирает размер файла. */
  sizes?: string;
  /** Единственный кадр первого экрана грузится вперёд всего остального. */
  priority?: boolean;
  /**
   * 75 хватает тёмной фотографии. 82 — снимкам интерфейса, которые ложатся
   * текстурой на стекло устройства: там мелкий текст и артефакты видны сразу.
   */
  quality?: 75 | 82;
};

export function Photo({
  src,
  alt = '',
  className,
  sizes = '100vw',
  priority = false,
  quality = 75,
}: PhotoProps) {
  return (
    <Image
      className={className ? `photo ${className}` : 'photo'}
      src={src}
      alt={alt}
      fill
      sizes={sizes}
      quality={quality}
      priority={priority}
      /* Всё, кроме первого экрана, ждёт своей очереди у браузера. */
      loading={priority ? undefined : 'lazy'}
      decoding="async"
      draggable={false}
    />
  );
}
