/**
 * Фотография, лежащая во весь свой слой.
 *
 * На странице их семь: свет за первым экраном, интерьер салона за сценой
 * роста, столик кафе за клиентской секцией, барбер за финальным призывом,
 * снимок мастера в соло-секции и обложки внутри мокапов страницы записи.
 * Раскладываются все одинаково — заполнить родителя, обрезать по кадру, не
 * мешать тому, что лежит поверх, — поэтому и компонент один.
 *
 * Через `next/image`, а не `<picture>` с заранее собранными WebP: оптимизатор
 * отдаёт AVIF, выбирает ширину под экран и откладывает всё, что не в первом
 * кадре. Присланная сборка возила один и тот же файл на телефон и на 5K.
 *
 * Родительский слой обязан быть спозиционирован — `fill` раскладывается по
 * нему абсолютно.
 */
import Image from 'next/image';

type StillProps = {
  /** Путь в /public — без расширения размера: файл один, ширины считает Next. */
  src: string;
  /** Пусто для декораций: слой без собственного сообщения читалке не нужен. */
  alt?: string;
  className?: string;
  /** Ширина слоя на экране — из неё оптимизатор выбирает размер файла. */
  sizes?: string;
  /** Единственный кадр первого экрана грузится вперёд остального. */
  priority?: boolean;
};

export function Still({ src, alt = '', className, sizes = '100vw', priority = false }: StillProps) {
  return (
    <Image
      className={className}
      src={src}
      alt={alt}
      fill
      sizes={sizes}
      quality={75}
      priority={priority}
      loading={priority ? undefined : 'lazy'}
      decoding="async"
      draggable={false}
    />
  );
}
