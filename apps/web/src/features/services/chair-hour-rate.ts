/**
 * Цена часа кресла у самой услуги — от прайса, а не от истории.
 *
 * «Финансы» считают час кресла по завершённым визитам, то есть говорят о
 * прошлом и только раз в разделе, куда мастер заходит редко. У самой услуги
 * час считается точно и без всякой истории: цена, делённая на время, которое
 * услуга держит календарь. Это и есть то, что сравнивают, выбирая, чем
 * заполнить день.
 *
 * Делится на минуты самой услуги, без уборки после неё. Соблазн считать по
 * следу визита («75 мин с буфером 15 держат полтора часа») велик, но «Финансы»
 * считают час кресла по завершённым визитам, а в них буфера нет: он не
 * хранится в позиции визита и восстановить его задним числом нельзя. Разные
 * знаменатели давали одной услуге два разных часа на соседних экранах — прайс
 * «40 €/ч», вывод финансов «56 € в час», — и продукт опровергал сам себя
 * (критика 2026-09-28). Одна мера важнее более точной.
 *
 * `null` там, где считать нечего: без времени час не считается, а у цены «от»
 * он был бы обещанием, которого прайс не даёт. У часовой услуги он повторяет
 * её цену и всё равно печатается: колонка сравнения, в которой три строки из
 * восьми пусты, сравнивать не даёт, а «Финансы» берут эталоном как раз
 * часовую услугу (критика 2026-09-29).
 */
export function chairHourOfService(service: {
  priceAmount: number;
  priceType?: string;
  durationMinutes: number;
}): number | null {
  if (service.priceType === 'from') return null;
  const minutes = service.durationMinutes;
  if (minutes <= 0 || service.priceAmount <= 0) return null;
  return Math.round(service.priceAmount / (minutes / 60));
}
