import { describe, expect, it } from 'vitest';

import { joinLocal, splitLocal } from './local-time';

/**
 * Поля переноса живут в часовом поясе заведения, а момент — в UTC.
 *
 * Ошибка здесь тихая: перепутанный пояс сдвигает визит на час, и замечает это
 * клиент, пришедший не вовремя. Отсюда проверки на обе стороны перехода и
 * отдельно — на летнее и зимнее время, где постоянная поправка ошиблась бы
 * дважды в год.
 */
describe('splitLocal — момент в поля', () => {
  it('показывает время заведения, а не UTC', () => {
    // 2 сентября 07:30 UTC — это 10:30 в Риге (летом +03:00).
    expect(splitLocal('2026-09-02T07:30:00.000Z', 'Europe/Riga')).toEqual({
      date: '2026-09-02',
      time: '10:30',
    });
  });

  it('зимой поправка другая, и это видно', () => {
    // 15 января 08:00 UTC — 10:00 в Риге (зимой +02:00).
    expect(splitLocal('2026-01-15T08:00:00.000Z', 'Europe/Riga')).toEqual({
      date: '2026-01-15',
      time: '10:00',
    });
  });
});

describe('joinLocal — поля обратно в момент', () => {
  it('час заведения превращается в правильный UTC', () => {
    expect(joinLocal('2026-09-05', '16:00', 'Europe/Riga')).toBe('2026-09-05T13:00:00.000Z');
  });

  it('зимний час считается своей поправкой', () => {
    expect(joinLocal('2026-01-15', '10:00', 'Europe/Riga')).toBe('2026-01-15T08:00:00.000Z');
  });

  it('переход туда и обратно ничего не сдвигает', () => {
    const iso = '2026-09-02T07:30:00.000Z';
    const { date, time } = splitLocal(iso, 'Europe/Riga');

    expect(joinLocal(date, time, 'Europe/Riga')).toBe(iso);
  });

  it('пустые поля — это «ничего не выбрано», а не полночь', () => {
    expect(joinLocal('', '16:00', 'Europe/Riga')).toBeNull();
    expect(joinLocal('2026-09-05', '', 'Europe/Riga')).toBeNull();
  });
});
