-- Кому показывать объявление.
--
-- В артборде панели у объявления есть адресат: «всем», «мастерам»,
-- «салонам». До этого объявление видели все подряд, и написать салонам про
-- сотрудников значило показать это же мастерам-одиночкам, у которых
-- сотрудников нет.
--
-- Умолчание — «всем»: ровно то поведение, которое было до этой колонки, и
-- существующие объявления его сохраняют.
CREATE TYPE "announcement_audience" AS ENUM ('all', 'masters', 'salons');--> statement-breakpoint
ALTER TABLE "announcements" ADD COLUMN "audience" "announcement_audience" DEFAULT 'all' NOT NULL;
