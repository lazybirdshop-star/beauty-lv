-- Заметка платформы об аккаунте.
--
-- В артборде карточки мастера есть блок «Admin notes»: «спрашивала про
-- переход на салон 20 августа, ждёт второго мастера». Такому знанию сейчас
-- негде жить — оно остаётся в голове того, кто разбирал обращение, и
-- следующий разбор начинается с нуля.
--
-- Колонка на пользователе, а не на организации: вопросы в поддержку задаёт
-- человек, и переезд из одиночки в салон не должен обнулять историю
-- разговора с ним.
--
-- Заметку видит только панель платформы. Мастеру она не показывается нигде:
-- это записи о человеке, а не для него.
ALTER TABLE "users" ADD COLUMN "admin_note" text;
