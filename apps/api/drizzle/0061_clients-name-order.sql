-- Адресная книга открывается отсортированной по имени.
--
-- Единственный индекс на `clients` — уникальный `(organization_id, phone)`, а
-- список сортируется по `full_name`: у мастера с восемью сотнями клиентов это
-- сортировка всей книги на каждое открытие самого частого экрана кабинета.
-- Порядок колонок тот же, что у запроса: организация ведущая, имя вторым, — и
-- тогда сортировка достаётся бесплатно вместе с отбором.
--
-- Мягко удалённые из индекса исключены: их в списке нет никогда, а держать в
-- нём карточки, которые мастер убрала, — платить за строки, которых не
-- спрашивают.
CREATE INDEX IF NOT EXISTS "clients_organization_id_full_name_idx"
  ON "clients" USING btree ("organization_id","full_name") WHERE "deleted_at" IS NULL;
