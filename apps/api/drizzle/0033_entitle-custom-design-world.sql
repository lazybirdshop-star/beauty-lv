/*
 * Заказной мир становится правом, а не догадкой.
 *
 * Каталог оформления открыт всем, и мир, скрытый из галереи, до сих пор
 * оставался доступен любому, кто пришлёт его ключ прямо в API: скрытие жило
 * в вебе и было решением о показе, а не о доступе. Для мира, нарисованного
 * под конкретную студию, это значит, что работа, за которую она заплатила,
 * достаётся всем угадавшим строку.
 *
 * Колонка называет выдачу поимённо: единственный ключ вне предложения
 * каталога, который этой организации разрешено на себя поставить. `NULL` —
 * не выдавали ничего, и тогда разрешено ровно предложение.
 *
 * Ни одна существующая строка не меняется: до сих пор заказных миров не
 * выдавали никому, и `NULL` это ровно то состояние, в котором они все и так
 * находятся. Страницы, стоящие на снятых мирах, тоже не трогаются — их
 * защищает не эта колонка, а откат на текущий облик в санитайзере.
 */
