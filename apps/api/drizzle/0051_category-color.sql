-- Цвет категории услуг.
--
-- В артборде `ServicesCategories.dc.html` у каждой категории стоит кружок
-- цвета — в списке и в предпросмотре страницы записи. Цвет уже есть у услуги
-- (`services.color`), и раскрашивать календарь по категориям было нечем:
-- мастер задавала цвет каждой услуге по отдельности.
--
-- NULL — «цвет не выбран», ровно как у услуги: кружок в этом случае серый, и
-- выдумывать за мастера цвет никто не будет.
ALTER TABLE "service_categories" ADD COLUMN "color" text;
