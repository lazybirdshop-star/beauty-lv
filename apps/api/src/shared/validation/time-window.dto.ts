import { IsISO8601, IsOptional } from 'class-validator';

/**
 * Отрезок времени, за который спрашивают список.
 *
 * Оба конца необязательны, и это не поблажка, а два разных вопроса: главная
 * спрашивает одни сутки (`from` и `to`), календарь — «от сегодня и дальше»
 * (только `from`). Отсутствие обоих означает «всё» — так список вёл себя
 * всегда, и старые вызовы обязаны продолжать работать.
 *
 * Границы приходят полными метками времени, а не датами: сутки мастера —
 * это сутки её салона, и кто именно считает их начало, решено на стороне
 * кабинета, который единственный знает пояс организации. Сервер получает уже
 * посчитанный момент и не имеет своего мнения о том, когда начинается день.
 *
 * Полуинтервал `[from, to)`: смежные сутки не могут ни поделить одну запись,
 * ни потерять её. Закрытый справа отрезок отдал бы полночь обоим дням.
 */
export class TimeWindowDto {
  @IsOptional()
  @IsISO8601()
  from?: string;

  @IsOptional()
  @IsISO8601()
  to?: string;
}

/** Разобранное окно — то, что репозиторий умеет положить в `where`. */
export interface TimeWindow {
  from?: Date;
  to?: Date;
}

/**
 * Границы — в `Date`, отсутствующие остаются отсутствующими.
 *
 * Отдельной функцией, а не методом DTO: репозиториям нужен разобранный тип, и
 * протаскивать в них класс с декораторами валидации значило бы тащить слой
 * представления внутрь инфраструктуры.
 */
export function parseTimeWindow(dto: TimeWindowDto): TimeWindow {
  return {
    from: dto.from ? new Date(dto.from) : undefined,
    to: dto.to ? new Date(dto.to) : undefined,
  };
}
