import { normalizePhone, phoneMatchKey } from '@amolie/shared-kernel';

/**
 * Пополнение адресной книги мастера записью.
 *
 * Здесь проверяется правило, из-за которого в живой базе завелись две «Ilva
 * Bērziņa»: уникальный индекс `(organization_id, phone)` сравнивает строки, а
 * `normalizePhone` доводит до строки только запись разделителей — код страны
 * он сохраняет намеренно, чтобы мастер могла набрать сохранённое. Значит
 * «20000114» и «+37120000114» остаются двумя разными строками, конфликта нет,
 * и человек заводится дважды.
 *
 * `phoneMatchKey` отвечает на другой вопрос — «тот же ли это человек» — и
 * именно он теперь решает, обновить существующую строку или завести новую.
 * Тест держит инвариант на уровне ключей, а не на уровне SQL: сама выборка —
 * зеркало `phoneMatchKey` в постгресе, и если ключи перестанут совпадать,
 * зеркало не спасёт.
 */

/** Как записан номер одного и того же латвийского абонента в жизни. */
const SAME_SUBSCRIBER = [
  '+37120000114',
  '+371 20 000 114',
  '+371-20-000-114',
  '0037120000114',
  '20000114',
  '20 000 114',
];

describe('адресная книга: когда это один человек', () => {
  it('одна и та же строка после нормализации — очевидный случай', () => {
    expect(normalizePhone('+371 20 000 114')).toBe('+37120000114');
    expect(normalizePhone('+371-20-000-114')).toBe('+37120000114');
    expect(normalizePhone('0037120000114')).toBe('+37120000114');
  });

  it('нормализации мало: местная и международная записи дают разные строки', () => {
    // Ровно та дыра, через которую прошёл дубль. Индекс по строке её не видит.
    expect(normalizePhone('20000114')).not.toBe(normalizePhone('+37120000114'));
  });

  it('ключ совпадения сводит все шесть записей к одному человеку', () => {
    const keys = new Set(SAME_SUBSCRIBER.map(phoneMatchKey));

    expect(keys.size).toBe(1);
    expect([...keys][0]).toBe('20000114');
  });

  it('разные абоненты не склеиваются', () => {
    // Восемь значащих цифр — не меньше: на более коротком хвосте начали бы
    // сталкиваться посторонние люди.
    expect(phoneMatchKey('+37120000114')).not.toBe(phoneMatchKey('+37120000115'));
    expect(phoneMatchKey('+37120000114')).not.toBe(phoneMatchKey('+37129000114'));
  });

  it('короткий номер сравнивается целиком, а не хвостом', () => {
    expect(phoneMatchKey('112')).toBe('112');
    expect(phoneMatchKey('+371112')).toBe('371112');
  });
});

describe('адресная книга: что попадает в базу', () => {
  it('хранится нормализованная запись, а не то, что набрал гость', () => {
    // Мастер должна суметь набрать сохранённое, поэтому код страны остаётся,
    // а разделители — нет.
    for (const written of ['+371 20 000 114', '+371-20-000-114', '0037120000114']) {
      expect(normalizePhone(written)).toBe('+37120000114');
    }
  });

  it('местный номер сохраняется как есть — придумывать ему код страны нечем', () => {
    // Пакет не знает, какой стране принадлежит местный номер, и не угадывает.
    expect(normalizePhone('20 000 114')).toBe('20000114');
  });

  it('пустой номер не даёт ключа — по нему никого искать нельзя', () => {
    // Иначе выборка «хвост длиной 0» совпала бы с любой строкой в книге.
    expect(phoneMatchKey('')).toBe('');
    expect(phoneMatchKey('   ')).toBe('');
  });
});
