import { IsUUID } from 'class-validator';

/**
 * Какую карточку поглотить.
 *
 * Оставляемая приходит адресом (`:clientId`), поглощаемая — телом. Так
 * читается сам запрос: «в этого клиента влить вот того», и путь называет ту
 * карточку, которая после операции останется.
 */
export class MergeClientDto {
  @IsUUID()
  mergeId!: string;
}
