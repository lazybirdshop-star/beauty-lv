import { IsInt, IsOptional, Min } from 'class-validator';

/**
 * Публикация. Решения по ручкам приходят объектом и разбираются
 * `sanitizePageDesign` (DESIGN_STUDIO.md §7.4) — здесь описан только конверт.
 *
 * `design` не описан декораторами намеренно: правила ручек измеримые
 * (каталоги, контраст) и живут в `shared-kernel` вместе с резолвером, который
 * рисует страницу. Второе описание тех же правил здесь однажды разошлось бы
 * с первым, а расхождение между тем, что сервер принял, и тем, что страница
 * нарисовала, — ровно тот дефект, который §7.4 обязан исключить.
 *
 * Пустое тело — законный запрос: он публикует текущий черновик.
 */
export class PublishPageDesignDto {
  @IsOptional()
  design?: unknown;
}

export class RollbackPageDesignDto {
  @IsInt()
  @Min(1)
  version!: number;
}
