/**
 * Что видит человек на экране заблокированного телефона.
 *
 * Отдельный тип, а не аргументы отправки: текст уведомления собирается по
 * локали получателя в одном месте, а инфраструктура его только шифрует и
 * передаёт, ничего не зная про записи и про мастеров.
 */
export interface PushMessage {
  title: string;
  body: string;
  /** Путь внутри кабинета, который откроет нажатие. Всегда относительный. */
  url: string;
  /**
   * Группа схлопывания: уведомления с одинаковым тегом заменяют друг друга,
   * а не копятся стопкой. Для новых записей тег содержит id записи — три
   * разные записи обязаны остаться тремя строками, иначе мастер увидит
   * последнюю и не узнает про две первые.
   */
  tag: string;
}

/**
 * Чем закончилась попытка доставки — ровно три исхода, которые вызывающему
 * нужно различать.
 *
 * `expired` отделён от `failed` намеренно: push-сервис отвечает 404/410, когда
 * подписки больше нет (браузер переустановлен, разрешение отозвано, устройство
 * потеряно). Это не сбой, а сообщение «этого адреса больше не существует», и
 * единственная правильная реакция — удалить строку. Считать его ошибкой значит
 * вечно писать на мёртвый адрес.
 */
export type PushDeliveryResult = 'delivered' | 'expired' | 'failed';
