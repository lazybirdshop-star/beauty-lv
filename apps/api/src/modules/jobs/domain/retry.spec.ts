import { retryDelayMs, STUCK_AFTER_MS } from './retry';

/**
 * Отсрочка повтора — не украшение: она решает, догонит ли письмо о записи сам
 * визит. Поэтому проверяются оба свойства, ради которых она такая: рост и
 * потолок.
 */
describe('retryDelayMs', () => {
  it('растёт вдвое от попытки к попытке', () => {
    expect(retryDelayMs(1)).toBe(30_000);
    expect(retryDelayMs(2)).toBe(60_000);
    expect(retryDelayMs(3)).toBe(120_000);
  });

  it('упирается в потолок', () => {
    /* Без потолка шестая попытка ушла бы на часы вперёд, и подтверждение
       записи пришло бы клиенту после визита. */
    expect(retryDelayMs(10)).toBe(30 * 60_000);
    expect(retryDelayMs(99)).toBe(30 * 60_000);
  });

  it('нулевая попытка не даёт отрицательной степени', () => {
    expect(retryDelayMs(0)).toBe(30_000);
  });

  it('брошенной задача считается позже любого разумного обработчика', () => {
    // Все обработчики упираются в один HTTP-запрос к провайдеру.
    expect(STUCK_AFTER_MS).toBeGreaterThan(60_000);
  });
});
