/**
 * Через сколько повторить упавшую задачу.
 *
 * Растёт вдвое от попытки к попытке: почтовый провайдер, который не ответил
 * сейчас, чаще всего не ответит и через секунду, а вот через минуту —
 * вероятно. Постоянный интервал в этой ситуации превращает наш повтор в
 * маленькую атаку на того, кто и так лежит.
 *
 * Потолок есть, и он важнее самого роста: без него шестая попытка ушла бы на
 * сутки вперёд, и письмо о записи пришло бы клиенту после визита.
 */
const BASE_DELAY_MS = 30_000;
const MAX_DELAY_MS = 30 * 60_000;

export function retryDelayMs(attempts: number): number {
  const growth = BASE_DELAY_MS * 2 ** Math.max(0, attempts - 1);
  return Math.min(growth, MAX_DELAY_MS);
}

/**
 * Когда считать взятую задачу брошенной.
 *
 * Машина может умереть между «взял» и «сделал» — тогда строка навсегда
 * останется в `running`, а письмо не уйдёт никогда. Никакой блокировки,
 * которая переживёт смерть процесса, у нас нет, поэтому единственный признак
 * — время: задача, взятая слишком давно, возвращается в очередь.
 *
 * Пятнадцать минут — заведомо больше любого нашего обработчика (все они
 * упираются в один HTTP-запрос к провайдеру) и заведомо меньше терпения
 * клиента, ждущего письма.
 */
export const STUCK_AFTER_MS = 15 * 60_000;
