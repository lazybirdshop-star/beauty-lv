import { IsISO8601 } from 'class-validator';

/**
 * Отрезок, за который снимаются свободные окна.
 *
 * Обе границы обязательны — в отличие от `TimeWindowDto`, где они
 * необязательны и «ничего не задано» значит «всё». Для чтения это разумное
 * умолчание; для удаления оно означало бы «снять вообще всё», причём как ответ
 * на запрос, в котором мастер просто ничего не выбрала. Требование обеих
 * границ делает такой запрос невозможным, а не маловероятным.
 */
export class DeleteSlotsRangeDto {
  @IsISO8601()
  from!: string;

  @IsISO8601()
  to!: string;
}
