import { IsBoolean } from 'class-validator';

/**
 * Скрыть окно или вернуть его на страницу записи.
 *
 * Булево поле, а не два маршрута (`/hide` и `/show`): состояние у окна одно,
 * и запрос «пусть будет скрыто» идемпотентен — повторное нажатие в двух
 * вкладках не должно давать разный результат в зависимости от порядка.
 */
export class SetSlotVisibilityDto {
  @IsBoolean()
  hidden!: boolean;
}
